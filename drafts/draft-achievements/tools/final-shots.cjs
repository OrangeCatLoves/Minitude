// Builds final.html (six designs of the last achievement) from src/final.template.html (the pixel toolkit is taken from src/icons.template.html) and
// takes designs/final-sheet.png.   MINITUDE_CHANNEL=chrome node final-shots.cjs
const fs = require('fs'), path = require('path'), { pathToFileURL } = require('url')
const { chromium } = require('../../../tools/browser-test/node_modules/playwright')
const ROOT = path.join(__dirname, '..')
const icons = fs.readFileSync(path.join(ROOT, 'src', 'icons.template.html'), 'utf8')
const a = icons.indexOf('const RAINBOW'), b = icons.indexOf('/* ---------- the 15 pictograms')
if (a < 0 || b < 0) throw new Error('toolkit markers not found in icons.template.html')
const page = fs.readFileSync(path.join(ROOT, 'src', 'final.template.html'), 'utf8').replace('/*TOOLKIT*/', icons.slice(a, b))
fs.writeFileSync(path.join(ROOT, 'final.html'), page)
;(async () => {
  const br = await chromium.launch({ channel: process.env.MINITUDE_CHANNEL || 'chrome' })
  const p = await br.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1 })
  const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()) })
  await p.goto(pathToFileURL(path.join(ROOT, 'final.html')).href)
  await p.waitForSelector('body.ready'); await p.waitForTimeout(500)
  await (await p.$('#sheet')).screenshot({ path: path.join(ROOT, 'designs', 'final-sheet.png') })
  await br.close()
  console.log(errs.length ? 'ERRORS: ' + errs.join(' | ') : 'no page errors', '| wrote designs/final-sheet.png')
})().catch((e) => { console.error(e); process.exit(1) })
